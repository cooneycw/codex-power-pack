@pytest.mark.parametrize(
    "replacement, message",
    [
        ("commit: abc", "40 lowercase"),
        ("commit: {commit}\ncommit: {commit}", "duplicate field 'commit'"),
        ("unknown: value", "unknown field 'unknown'"),
        ("pulls: ../skills/  ->  .codex/skills/", "escapes its root"),
        ("pulls: codex/skills/  ->  ../../outside/", "escapes its root"),
    ],
)
def test_pin_rejects_malformed_duplicate_and_unsafe_fields(
    provenance_fixture: tuple[Path, Path, str], replacement: str, message: str
) -> None:
    _, _, commit = provenance_fixture
    text = sync.PIN_PATH.read_text(encoding="utf-8")
    if replacement.startswith("commit:"):
        text = text.replace(f"commit: {commit}", replacement.format(commit=commit))
    elif replacement.startswith("pulls:"):
        text = text.replace(
            "pulls: codex/skills/  ->  .codex/skills/", replacement
        )
    else:
        text += replacement + "\n"
    sync.PIN_PATH.write_text(text, encoding="utf-8")

    with pytest.raises(sync.IntegrityError, match=message):
        sync.read_pin()


