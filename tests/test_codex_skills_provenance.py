@pytest.mark.parametrize("failure", ["dirty", "head-mismatch", "unsafe-destination"])
def test_refresh_validation_failure_preserves_every_published_byte(
    provenance_fixture: tuple[Path, Path, str], tmp_path: Path, failure: str
) -> None:
    root, source, commit = provenance_fixture
    before = _tree_bytes(root)

    if failure == "dirty":
        (source / "untracked.txt").write_text("dirty\n", encoding="utf-8")
        refresh_ref = commit
    elif failure == "head-mismatch":
        _git(source, "switch", "-q", "--detach")
        (source / "later.txt").write_text("later\n", encoding="utf-8")
        _git(source, "add", "later.txt")
        _git(source, "commit", "-q", "-m", "later source")
        refresh_ref = commit
    else:
        outside = tmp_path / "outside-destination"
        outside.mkdir()
        (sync.SKILLS_ROOT / "escape").symlink_to(outside, target_is_directory=True)
        before = _tree_bytes(root)
        refresh_ref = commit

    assert sync.run_refresh(source, refresh_ref) == 2
    assert _tree_bytes(root) == before
