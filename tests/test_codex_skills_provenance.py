def test_validated_refresh_publishes_frozen_payload_and_preserves_local_overlays(
    provenance_fixture: tuple[Path, Path, str], monkeypatch: pytest.MonkeyPatch
) -> None:
    _, source, _ = provenance_fixture
    metadata = sync.PLUGINS_ROOT / "flow" / "skills" / "flow-auto" / "agents" / "openai.yaml"
    metadata_before = metadata.read_bytes()
    native = sync.SKILLS_ROOT / "project-next" / "SKILL.md"
    native.parent.mkdir()
    native.write_text("native\n", encoding="utf-8")
    stale_agent_payload = (
        sync.PLUGINS_ROOT
        / "flow"
        / "skills"
        / "flow-auto"
        / "agents"
        / "stale-runtime.txt"
    )
    stale_agent_payload.write_text("stale\n", encoding="utf-8")

    _git(source, "switch", "-q", "main")
    helper = source / "codex" / "skills" / "flow-auto" / "scripts" / "fixture.sh"
    helper.write_text("#!/usr/bin/env bash\necho refreshed\n", encoding="utf-8")
    source_agent_payload = (
        source / "codex" / "skills" / "flow-auto" / "agents" / "runtime.txt"
    )
    source_agent_payload.parent.mkdir()
    source_agent_payload.write_text("source-owned runtime\n", encoding="utf-8")
    _git(source, "add", ".")
    _git(source, "commit", "-q", "-m", "refreshed CPP source")
    commit = _git(source, "rev-parse", "HEAD")
    _git(source, "checkout", "-q", "--detach", commit)
    # Re-adopt at the NEW commit. `_validate_policy_source` binds the policy to an
    # exact source commit and tree, so refreshing to a new source without moving
    # the policy is the coordinated-update failure #254 is about - here it simply
    # means the fixture must declare the new source adopted before refreshing it.
    _install_synthetic_adoption_policy(source, commit, monkeypatch)

    assert sync.run_refresh(source, commit) == 0
    assert sync.read_pin().commit == commit
    assert (sync.SKILLS_ROOT / "flow-auto" / "scripts" / "fixture.sh").read_text(
        encoding="utf-8"
    ).endswith("echo refreshed\n")
    assert metadata.read_bytes() == metadata_before
    assert (
        sync.PLUGINS_ROOT
        / "flow"
        / "skills"
        / "flow-auto"
        / "agents"
        / "runtime.txt"
    ).read_text(encoding="utf-8") == "source-owned runtime\n"
    assert not stale_agent_payload.exists()
    assert native.read_text(encoding="utf-8") == "native\n"
    assert sync.compute_manifest() == sync.read_manifest()
    assert sync.run_pin_check(source) == 0


