def test_exact_pin_rejects_assume_unchanged_forged_source_and_generated_payload(
    provenance_fixture: tuple[Path, Path, str]
) -> None:
    _, source, _ = provenance_fixture
    source_skill = source / "codex" / "skills" / "flow-auto"
    source_file = source_skill / "SKILL.md"
    _git(source, "update-index", "--assume-unchanged", "codex/skills/flow-auto/SKILL.md")
    source_file.write_text(
        "---\nname: flow-auto\n---\n<!-- GENERATED by claude-power-pack -->\nforged\n",
        encoding="utf-8",
    )
    assert _git(source, "status", "--porcelain", "--untracked-files=all") == ""

    # Even a forged source mirrored into generated/plugin payloads and the manifest
    # cannot bless bytes that are absent from the immutable pinned Git tree.
    payloads = sync._adapted_source_payloads(source_skill)
    sync._write_skill_payload(sync.SKILLS_ROOT / "flow-auto", payloads)
    sync._sync_plugin_payload("flow-auto")
    assert sync.run_write() == 0

    assert sync.run_pin_check(source) == 1


