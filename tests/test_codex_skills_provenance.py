def _git(root: Path, *args: str) -> str:
    completed = subprocess.run(
        ["git", *args],
        cwd=root,
        env=GIT_ENV,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    )
    return completed.stdout.strip()


def _source_repo(tmp_path: Path, *, origin: str = sync.CPP_REPO_URL) -> tuple[Path, str]:
    source = tmp_path / "cpp"
    skill = source / "codex" / "skills" / "flow-auto"
    skill.mkdir(parents=True)
    (skill / "SKILL.md").write_text(
        "---\nname: flow-auto\n---\n<!-- GENERATED by claude-power-pack -->\n",
        encoding="utf-8",
    )
    helper = skill / "scripts" / "fixture.sh"
    helper.parent.mkdir()
    helper.write_text("#!/usr/bin/env bash\necho fixture\n", encoding="utf-8")
    helper.chmod(0o755)

    _git(source, "init", "-q", "-b", "main")
    _git(source, "remote", "add", "origin", origin)
    _git(source, "add", ".")
    _git(source, "commit", "-q", "-m", "fixture CPP source")
    commit = _git(source, "rev-parse", "HEAD")
    _git(source, "checkout", "-q", "--detach", commit)
    return source, commit


def _configure_destination(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    root = tmp_path / "cxpp"
    skills = root / ".codex" / "skills"
    vendor = root / "vendor" / "claude-power-pack"
    plugins = root / "plugins"
    skills.mkdir(parents=True)
    vendor.mkdir(parents=True)
    plugins.mkdir(parents=True)
    contracts = root / ".agents" / "skill-contracts.json"
    contracts.parent.mkdir(parents=True)
    contracts.write_text(
        json.dumps(
            {
                "skills": [
                    {
                        "name": "flow-auto",
                        "package": {
                            "state": "packaged",
                            "path": "plugins/flow/skills/flow-auto",
                        },
                    }
                ]
            }
        ),
        encoding="utf-8",
    )
    monkeypatch.setattr(sync, "REPO_ROOT", root)
    monkeypatch.setattr(sync, "SKILLS_ROOT", skills)
    monkeypatch.setattr(sync, "VENDOR_DIR", vendor)
    monkeypatch.setattr(sync, "MANIFEST_PATH", vendor / "codex-skills.sha256")
    monkeypatch.setattr(sync, "PIN_PATH", vendor / "PIN")
    monkeypatch.setattr(sync, "PLUGINS_ROOT", plugins)
    return root


def _publish_fixture(source: Path, commit: str) -> None:
    source_skill = source / "codex" / "skills" / "flow-auto"
    generated = sync.SKILLS_ROOT / "flow-auto"
    payloads = sync._adapted_source_payloads(source_skill)
    sync._write_skill_payload(generated, payloads)

    packaged = sync.PLUGINS_ROOT / "flow" / "skills" / "flow-auto"
    for rel, payload in payloads.items():
        target = packaged / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload.content)
        target.chmod(payload.mode)
    metadata = packaged / "agents" / "openai.yaml"
    metadata.parent.mkdir()
    metadata.write_text("interface: fixture-only metadata\n", encoding="utf-8")

    sync._write_pin(commit)
    assert sync.run_write() == 0


@pytest.fixture
def provenance_fixture(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> tuple[Path, Path, str]:
    root = _configure_destination(tmp_path, monkeypatch)
    source, commit = _source_repo(tmp_path)
    _publish_fixture(source, commit)
    return root, source, commit


def _tree_bytes(root: Path) -> dict[str, bytes]:
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in root.rglob("*")
        if path.is_file() and ".git" not in path.relative_to(root).parts
    }


